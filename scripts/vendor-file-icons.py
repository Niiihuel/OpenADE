#!/usr/bin/env python3
"""Refresh the pinned, MIT-licensed Material Icon Theme subset; no npm execution.

Run from any directory with Python 3. Downloads one integrity-checked archive,
copies only selected SVGs/LICENSE and generates sorted Rust lookup tables.
"""
import base64
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request

VERSION = "5.38.1"
COMMIT = "448ab3977ef83b817c2c722ce7cd5034d195b39f"
URL = f"https://registry.npmjs.org/material-icon-theme/-/material-icon-theme-{VERSION}.tgz"
INTEGRITY = "sha512-14cFM4NJGdbuo68rIZTq9TSX0f5BtA6VF+eNX3zq23Z5NoEeVtM4Zn4PpZ0ERl++50jCBrywKFWXmOjbxf0xTA=="
FILES = """file document rust javascript typescript typescript-def react react_ts
python html css sass less stylus json yaml toml markdown docker git lock settings
xml vue svelte astro c cpp h hpp csharp java kotlin go ruby php swift dart console
powershell nix database image svg pdf zip font audio video webassembly hex license
readme test-js test-ts test-jsx npm nodejs tsconfig eslint prettier vite webpack
cmake makefile tune graphql table log diff terraform lua r scala elixir proto zig
gradle maven jupyter kubernetes github-actions-workflow gitlab""".split()
FOLDERS = """folder folder-src folder-test folder-git folder-github folder-config
folder-docs folder-images folder-dist folder-public folder-node folder-resource
folder-packages folder-lib folder-components folder-api folder-routes folder-tools
folder-scripts folder-rust folder-buildkite folder-target folder-temp folder-log
folder-database folder-font folder-audio folder-video folder-vscode folder-home
folder-project folder-root folder-app folder-coverage folder-examples folder-ui
folder-typescript folder-javascript folder-python folder-docker folder-console""".split()


def main():
    root = Path(__file__).resolve().parents[1]
    destination = root / "crates/openide-ui/assets/material-icon-theme"
    data = urllib.request.urlopen(URL, timeout=60).read()
    actual = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if actual != INTEGRITY:
        raise ValueError("Upstream package integrity does not match the pin")
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as package:
        manifest = json.load(package.extractfile("package/dist/material-icons.json"))
        names = sorted(set(FILES + FOLDERS + [name + "-open" for name in FOLDERS]))
        indices = {name: i for i, name in enumerate(names)}
        checksums = {}
        for name in names:
            path = manifest["iconDefinitions"][name]["iconPath"].rsplit("/", 1)[-1]
            svg = package.extractfile(f"package/icons/{path}").read()
            (destination / f"{name}.svg").write_bytes(svg)
            checksums[f"{name}.svg"] = hashlib.sha256(svg).hexdigest()
        (destination / "LICENSE").write_bytes(package.extractfile("package/LICENSE").read())
    # The source mappings are filtered to artwork actually shipped. Language and
    # framework assets beyond this subset fall back deterministically to File.
    lines = ["// Generated by scripts/vendor-file-icons.py; do not edit.",
             f"// Material Icon Theme {VERSION} ({COMMIT}), MIT.",
             "pub(super) static ASSETS: &[(&str, &str)] = &["]
    for name in names:
        lines.append(f'    ("{name}", include_str!("../assets/material-icon-theme/{name}.svg")),')
    lines.append("];\n")
    for label, source in [("FILE_NAMES", "fileNames"), ("EXTENSIONS", "fileExtensions"),
                          ("LANGUAGES", "languageIds")]:
        entries = {key.lower(): indices[value] for key, value in manifest[source].items()
                   if value in indices}
        lines.append(f"pub(super) static {label}: &[(&str, u16)] = &[")
        lines.extend(f"    ({json.dumps(key, ensure_ascii=False)}, {value}),"
                     for key, value in sorted(entries.items()))
        lines.append("];\n")
    entries = {key.lower(): (indices[value], indices[manifest["folderNamesExpanded"][key]])
               for key, value in manifest["folderNames"].items() if value in FOLDERS}
    lines.append("pub(super) static FOLDERS: &[(&str, (u16, u16))] = &[")
    lines.extend(f"    ({json.dumps(key, ensure_ascii=False)}, ({value[0]}, {value[1]})),"
                 for key, value in sorted(entries.items()))
    lines.append("];\n")
    for label, name in [("DEFAULT_FILE", "file"), ("DEFAULT_FOLDER", "folder"),
                        ("DEFAULT_FOLDER_OPEN", "folder-open")]:
        lines.append(f"pub(super) const {label}: u16 = {indices[name]};")
    (root / "crates/openide-ui/src/file_icon_data.rs").write_text("\n".join(lines) + "\n")
    (destination / "SOURCE.json").write_text(json.dumps({
        "package": "material-icon-theme", "version": VERSION, "commit": COMMIT,
        "repository": "https://github.com/material-extensions/vscode-material-icon-theme",
        "archive": URL, "integrity": INTEGRITY, "sha256": checksums,
    }, indent=2, sort_keys=True) + "\n")
    print(f"Vendored {len(names)} SVGs with sorted upstream associations.")


if __name__ == "__main__":
    main()
